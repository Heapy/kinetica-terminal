#!/usr/bin/env python3
"""Generate XTGETTCAP replies and replay cases from unmodified Ghostty 1.4."""
import base64
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SHA = "83fb95624b0439ee660c2679b43b38c8b63769cd"

def cases():
    result = []
    for index, name in enumerate([None, "", "xterm-256color", "kinetica", "a"*128, "a"*129, "界"*42, "界"*43, "a\x00\n"]):
        result.append(dict(name=f"name_{index}", input="\x1bP+q544e;616d;544E\x1b\\", terminfo_name=name))
    for header in ["", "1", "1;2", "?", ">", "1:2", "+", " ", "1 ", "!"]:
        result.append(dict(name=f"header_{header}", input=f"\x1bP{header}+q436f\x1b\\"))
    for index, body in enumerate(["", ";", ";;436f;;616d;", "WHO;5;GG;436F", "436F\x00;616D", "436F\x07;616D", "ａ;436F", "436F;544e", "536D756C78;524742;4D73"]):
        result.append(dict(name=f"body_{index}", input=f"\x1bP+q{body}\x1b\\"))
    for end in ["\x18", "\x1a", "\x1b[0m", "\x1b\\"]:
        result.append(dict(name=f"end_{end.encode().hex()}", input="\x1bP+q436F"+end))
    for size in [4094, 4096, 1048576, 1048577]:
        result.append(dict(name=f"limit_{size}", prefix="\x1bP+q", repeated="X", count=size-5, suffix=";436F\x1b\\"))
    result.append(dict(name="reset_and_screens", input="\x1bP+q544E\x1b\\\x1bc\x1b[?1049h\x1bP+q544E\x1b\\", terminfo_name="xterm-256color"))
    return result

def main():
    upstream, zig = (Path(p).resolve() for p in sys.argv[1:3])
    assert subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=upstream, text=True).strip() == SHA
    subprocess.run(["git", "diff", "--exit-code", "HEAD", "--", "."], cwd=upstream, check=True, stdout=subprocess.DEVNULL)
    build = ROOT/"build/terminal-terminfo-oracle"; build.mkdir(parents=True, exist_ok=True)
    (build/"cases.json").write_text(json.dumps(cases(), ensure_ascii=True))
    helper = ROOT/"scripts/terminal-ghostty-terminfo-oracle.zig"
    shutil.copyfile(helper, build/"main.zig")
    # Zig forbids assigning one physical file to two modules. Use byte-identical copies for
    # table enumeration; the actual request oracle still uses Ghostty's own module instance.
    shutil.copytree(upstream/"src/terminfo", build/"terminfo", dirs_exist_ok=True)
    (build/"build.zig.zon").write_text('.{ .name = .zig_vt_stream, .version = "0.0.0", .fingerprint = 0x34c1f71303690b3f, .minimum_zig_version = "0.17.0", .dependencies = .{ .ghostty = .{ .path = '+json.dumps(os.path.relpath(upstream,build))+' } }, .paths = .{""} }')
    (build/"build.zig").write_text('''const std = @import("std");
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dep = b.dependency("ghostty", .{ .target = target, .optimize = .safe, .simd = false, .@"emit-lib-vt" = true, .@"emit-xcframework" = false });
    const root = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = target, .optimize = .safe, .link_libc = true });
    root.addImport("ghostty-vt", dep.module("ghostty-vt"));
    root.addImport("terminfo", b.createModule(.{ .root_source_file = b.path("terminfo/main.zig"), .target = target }));
    b.installArtifact(b.addExecutable(.{ .name = "terminfo-oracle", .root_module = root }));
}
''')
    env = os.environ | {"ZIG_GLOBAL_CACHE_DIR": str(ROOT/"build/upstream/zig-cache-0.17")}
    subprocess.run([str(zig), "build"], cwd=build, env=env, check=True)
    output = subprocess.run([str(build/"zig-out/bin/terminfo-oracle")], capture_output=True, text=True, check=True)
    records = [json.loads(line) for line in output.stdout.splitlines()]
    table = sorted((k,v) for k,v in zip(records[0]["keys"],records[0]["values"]) if k != "544E")
    assert all(len(k) <= 128 for k,v in table)
    generated = ROOT/"kinetica-terminal/src/generated/TerminalTerminfoCapabilities.kt"
    generated.parent.mkdir(parents=True, exist_ok=True)
    header = '// Generated by scripts/generate-terminal-terminfo.py; do not edit.\n// Ghostty 1.4.0 terminfo, MIT; see third-party/ghostty.json and GHOSTTY-LICENSE.\npackage io.heapy.kinetica.terminal\n\n'
    chunks = [table[i:i+64] for i in range(0,len(table),64)]
    text = header + 'internal val terminalTerminfoCapabilities: Map<String, String> by lazy { buildMap {\n'
    text += ''.join(f'    putAll(terminfoPart{i}())\n' for i in range(len(chunks))) + '} }\n'
    for i, chunk in enumerate(chunks):
        text += f'private fun terminfoPart{i}(): Map<String, String> = mapOf(\n'
        text += ''.join('    '+json.dumps(k)+' to '+json.dumps(v)+',\n' for k,v in chunk)+')\n'
    generated.write_text(text)
    fixture = ROOT/"kinetica-terminal/test/generated/TerminalTerminfoFixtures.kt"
    fixture.write_text(header+'internal fun terminalTerminfoFixtures(): List<String> = listOf(\n'+''.join('    "'+base64.b64encode(json.dumps(v,separators=(',',':')).encode()).decode()+'",\n' for v in records[1:])+')\n')
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    sources = ["src/terminfo/Source.zig", "src/terminfo/ghostty.zig", "src/terminal/dcs.zig", "src/terminal/stream_terminal.zig"]
    manifest = dict(commit=SHA, zig=subprocess.check_output([str(zig),"version"],text=True).strip(), capabilities=len(table), cases=len(records)-1,
        helperSha256=digest(helper), generatorSha256=digest(Path(__file__)), tableSha256=digest(generated), fixtureSha256=digest(fixture),
        sources={p:digest(upstream/p) for p in sources})
    (ROOT/"kinetica-terminal/test-upstream/ghostty/terminfo-manifest.json").write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Generated {len(table)} terminfo capabilities and {len(records)-1} original-handler cases')

if __name__ == "__main__": main()
