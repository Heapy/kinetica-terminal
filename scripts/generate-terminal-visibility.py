#!/usr/bin/env python3
"""Visibility protocol oracle using the unmodified pinned Ghostty Zig module."""
import base64
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SHA = "83fb95624b0439ee660c2679b43b38c8b63769cd"


def cases():
    result = []
    def add(name, events):
        result.append(dict(name=name, events=[dict(text=e) if isinstance(e, str) else dict(visible=e) for e in events]))
    query = "\x1b[?998n"
    mode = "\x1b[?2033$p"
    enable = "\x1b[?2033h"
    disable = "\x1b[?2033l"
    for initial in [True, False]:
        add(f"lifecycle_{initial}", [initial, mode+query, enable, enable, not initial, not initial, initial, disable, not initial, query+mode])
        add(f"resets_{initial}", [initial, enable, "\x1b[!p"+mode+query, not initial, "\x1bc"+mode+query, initial, query, enable])
        add(f"save_restore_{initial}", [initial, "\x1b[?2033s", enable, "\x1b[?2033r"+mode, not initial, enable+"\x1b[?2033s", disable, initial, "\x1b[?2033r", "\x1b[?2033r"])
        add(f"screens_and_hold_{initial}", [initial, enable+"\x1b[?1049h"+mode, not initial, "\x1b[?1049l\x1b[?2026h", initial, query+"\x1b[!p"+mode, not initial, "\x1b[?2026l"+query])
    add("invalid_forms", ["\x1b[998n\x1b[?998;0n\x1b[?998:0n\x1b[>998n\x1b[?998$n\x1b[?999n\x1b[2033h", False, mode+query, enable+disable+mode])
    add("partial_sequences", ["\x1b[?20", False, "33h", "\x1b[?998", True, "n", "\x1b]2;title", False, "\x07", query])
    add("mode_lists", [False, "\x1b[?2033;2033h", "\x1b[?2033;2033l", True, "\x1b[?2033;2004h", mode+query])
    return result


def main():
    upstream = Path(sys.argv[1]).resolve()
    zig = Path(sys.argv[2]).resolve()
    assert subprocess.check_output(["git","rev-parse","HEAD"],cwd=upstream,text=True).strip() == SHA
    subprocess.run(["git","diff","--exit-code","HEAD","--","."],cwd=upstream,check=True,stdout=subprocess.DEVNULL)
    build = ROOT/"build/terminal-visibility-oracle"
    build.mkdir(parents=True,exist_ok=True)
    corpus = cases()
    (build/"cases.json").write_text(json.dumps(corpus,ensure_ascii=True))
    helper = ROOT/"scripts/terminal-ghostty-visibility-oracle.zig"
    shutil.copyfile(helper,build/"main.zig")
    (build/"build.zig.zon").write_text('.{ .name = .zig_vt_stream, .version = "0.0.0", .fingerprint = 0x34c1f71303690b3f, .minimum_zig_version = "0.17.0", .dependencies = .{ .ghostty = .{ .path = '+json.dumps(os.path.relpath(upstream,build))+' } }, .paths = .{""} }')
    (build/"build.zig").write_text('''const std = @import("std");
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dep = b.dependency("ghostty", .{ .target = target, .optimize = .safe, .simd = false, .@"emit-lib-vt" = true, .@"emit-xcframework" = false });
    const root = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = target, .optimize = .safe, .link_libc = true });
    root.addImport("ghostty-vt", dep.module("ghostty-vt"));
    b.installArtifact(b.addExecutable(.{ .name = "visibility-oracle", .root_module = root }));
}
''')
    env = os.environ | {"ZIG_GLOBAL_CACHE_DIR":os.environ.get("ZIG_GLOBAL_CACHE_DIR",str(ROOT/"build/upstream/zig-cache-0.17"))}
    subprocess.run([str(zig),"build"],cwd=build,check=True,env=env)
    output = subprocess.run([str(build/"zig-out/bin/visibility-oracle")],capture_output=True,text=True)
    if output.returncode: print(output.stderr,file=sys.stderr)
    output.check_returncode()
    actual = [json.loads(line) for line in output.stdout.splitlines()]
    assert len(corpus) == len(actual)
    for case, result in zip(corpus,actual):
        assert case["name"] == result["name"]
        case["snapshots"] = result["snapshots"]
    fixture = ROOT/"kinetica-terminal/test/generated/TerminalVisibilityFixtures.kt"
    encoded = [base64.b64encode(json.dumps(c,separators=(',',':')).encode()).decode() for c in corpus]
    fixture.write_text('// Generated by scripts/generate-terminal-visibility.py; do not edit.\npackage io.heapy.kinetica.terminal\n\ninternal fun terminalVisibilityFixtures(): List<String> = listOf(\n'+''.join('    "'+v+'",\n' for v in encoded)+')\n')
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    manifest = dict(commit=SHA,zig=subprocess.check_output([str(zig),"version"],text=True).strip(),
        cases=len(corpus),snapshots=sum(len(c["snapshots"]) for c in corpus),
        hostAdapter="Changed visibility sets Terminal.flags.visible and asks the original handler for a report only when mode 2033 is enabled, mirroring Termio.visibilityReport.",
        helperSha256=digest(helper),generatorSha256=digest(Path(__file__)),fixtureSha256=digest(fixture),
        sources={p:digest(upstream/p) for p in ["src/terminal/Terminal.zig","src/terminal/stream_terminal.zig","src/terminal/device_status.zig","src/terminal/modes.zig","src/termio/Termio.zig"]})
    (ROOT/"kinetica-terminal/test-upstream/ghostty/visibility-manifest.json").write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Generated {len(corpus)} visibility cases / {manifest["snapshots"]} checkpoints')


if __name__ == "__main__": main()
