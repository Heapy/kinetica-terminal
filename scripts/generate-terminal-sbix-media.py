#!/usr/bin/env python3
"""Original deterministic JPEG/TIFF sbix artwork; no external image encoder."""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import runpy
import struct

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'scripts/generate-terminal-color-fonts.py'
OUTPUT = ROOT / 'kinetica-terminal/test-upstream/color-fonts'


def jpeg_gray(width, height, gray):
    """Baseline grayscale JPEG: constant 8x8 blocks, unit quantization, DC/EOB only."""
    def marker(code, data):
        return bytes([255, code]) + struct.pack('>H', len(data) + 2) + data
    dc = (gray - 128) * 8
    category = abs(dc).bit_length()
    assert category > 0
    # DC zero and the one nonzero category have codes 00/01; AC EOB has code 0.
    dc_table = bytes([0, 0, 2] + [0] * 14 + [0, category])
    ac_table = bytes([16, 1] + [0] * 15 + [0])
    amplitude = dc if dc >= 0 else (1 << category) - 1 + dc
    blocks = ((width + 7) // 8) * ((height + 7) // 8)
    bits = '01' + format(amplitude, f'0{category}b') + '0' + '000' * (blocks - 1)
    bits += '1' * (-len(bits) % 8)
    entropy = bytes(int(bits[i:i + 8], 2) for i in range(0, len(bits), 8)).replace(b'\xff', b'\xff\0')
    return (b'\xff\xd8' + marker(0xdb, b'\0' + bytes([1] * 64)) +
            marker(0xc0, struct.pack('>BHHBBBB', 8, height, width, 1, 1, 0x11, 0)) +
            marker(0xc4, dc_table + ac_table) + marker(0xda, bytes([1, 1, 0, 0, 63, 0])) + entropy + b'\xff\xd9')


def tiff_rgb(width, height, color):
    """Little-endian baseline TIFF, one uncompressed chunky RGB strip."""
    count = 10
    bits_offset = 8 + 2 + count * 12 + 4
    pixels_offset = bits_offset + 6
    values = [(256, 4, 1, width), (257, 4, 1, height), (258, 3, 3, bits_offset),
              (259, 3, 1, 1), (262, 3, 1, 2), (273, 4, 1, pixels_offset),
              (277, 3, 1, 3), (278, 4, 1, height), (279, 4, 1, width * height * 3), (284, 3, 1, 1)]
    return (b'II' + struct.pack('<HIH', 42, 8, count) +
            b''.join(struct.pack('<HHII', *entry) for entry in values) +
            struct.pack('<IHHH', 0, 8, 8, 8) + bytes(color) * (width * height))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    base = runpy.run_path(str(BASE))
    original, _ = base['generate']()
    png, _ = base['generate_sbix'](original)
    font = TTFont(io.BytesIO(png), recalcTimestamp=False)
    font['name'].setName('Kinetica Sbix Media Fixture', 1, 3, 1, 0x409)
    font['name'].setName('KineticaSbixMediaFixture-Regular', 6, 3, 1, 0x409)
    strikes = []
    for ppem, strike in font['sbix'].strikes.items():
        width, height = ppem // 2, ppem * 7 // 10
        gray = 96 if ppem == 20 else 176
        images = {}
        for name in ['A', 'B', 'D']:
            glyph = strike.glyphs[name]
            color = [32, 64, 240] if name == 'B' else [gray] * 3
            kind = 'jpg ' if name == 'A' else 'tiff'
            data = jpeg_gray(width, height, gray) if name == 'A' else tiff_rgb(width, height, color)
            glyph.graphicType = kind; glyph.imageData = data
            images[name] = dict(kind=kind, width=width, height=height, rgb=color,
                                origin=[glyph.originOffsetX, glyph.originOffsetY], base64=base64.b64encode(data).decode())
        strikes.append(dict(ppem=ppem, images=images))
    output = io.BytesIO(); font.save(output); data = output.getvalue()
    manifest = dict(fonttools=base['VERSION'], generatorSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                    baseGeneratorSha256=hashlib.sha256(BASE.read_bytes()).hexdigest(),
                    fontSha256=hashlib.sha256(data).hexdigest(), strikes=strikes)
    kotlin = '// Generated by scripts/generate-terminal-sbix-media.py. Original Apache-2.0 test artwork.\npackage io.heapy.kinetica.terminal\ninternal fun terminalSbixMediaFont(): String = "' + base64.b64encode(data).decode() + '"\n'
    artifacts = {OUTPUT / 'sbix-media.ttf': data,
                 OUTPUT / 'sbix-media-manifest.json': (json.dumps(manifest, indent=2) + '\n').encode(),
                 ROOT / 'kinetica-terminal/test@macosArm64/generated/TerminalSbixMediaFont.kt': kotlin.encode()}
    for path, content in artifacts.items():
        if args.check: assert path.read_bytes() == content, f'Stale fixture: {path}'
        else: path.write_bytes(content)
    print(f'{"Verified" if args.check else "Generated"} JPEG/TIFF sbix: {len(data)} bytes')


if __name__ == '__main__': main()
