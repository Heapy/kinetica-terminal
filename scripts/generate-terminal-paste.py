#!/usr/bin/env python3
"""Generate text-paste encoding and safety expectations using pinned original libghostty-vt."""
import base64
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SHA = "83fb95624b0439ee660c2679b43b38c8b63769cd"


def main():
    upstream, zig = (Path(value).resolve() for value in sys.argv[1:3])
    assert subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=upstream, text=True).strip() == SHA
    subprocess.run(["git", "diff", "--exit-code", "HEAD", "--", "."], cwd=upstream, check=True, stdout=subprocess.DEVNULL)
    cases = [dict(name=f"character_{code:02x}", text=chr(code)) for code in range(256)]
    for name, text in {
        "empty": "", "plain": "hello world", "lf": "a\nb\n", "cr": "a\rb\r",
        "crlf": "a\r\nb\r\n", "mixed_endings": "a\r\nb\nc\rd", "unicode": "界😀é\t\u2028\u2029",
        "closing_frame": "before\x1b[201~after\n", "opening_frame": "\x1b[200~text",
        "closing_only": "\x1b[201~", "closing_partial": "\x1b[201", "closing_c1": "\x9b201~",
        "closing_other": "\x1b[202~", "closing_split": "\x1b[20\x001~", "trailing_cr": "hello\r",
        "all_controls": "".join(chr(code) for code in range(32)) + "\x7f",
        "mixed_large": ("界\x03\r\n\x00\x1b[201~tail\t" * 300),
    }.items():
        cases.append(dict(name=name, text=text))
    build = ROOT / "build/terminal-paste-oracle"
    build.mkdir(parents=True, exist_ok=True)
    (build / "cases.json").write_text(json.dumps(cases, ensure_ascii=True))
    helper = ROOT / "scripts/terminal-ghostty-paste-oracle.zig"
    (build / "main.zig").write_bytes(helper.read_bytes())
    (build / "build.zig.zon").write_text('.{ .name = .zig_vt_stream, .version = "0.0.0", .fingerprint = 0x34c1f71303690b3f, .minimum_zig_version = "0.17.0", .dependencies = .{ .ghostty = .{ .path = ' + json.dumps(os.path.relpath(upstream, build)) + ' } }, .paths = .{""} }')
    (build / "build.zig").write_text('''const std = @import("std");
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dep = b.dependency("ghostty", .{ .target = target, .optimize = .safe, .simd = false, .@"emit-lib-vt" = true, .@"emit-xcframework" = false });
    const root = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = target, .optimize = .safe, .link_libc = true });
    root.addImport("ghostty-vt", dep.module("ghostty-vt"));
    b.installArtifact(b.addExecutable(.{ .name = "paste-oracle", .root_module = root }));
}
''')
    env = os.environ | {"ZIG_GLOBAL_CACHE_DIR": os.environ.get("ZIG_GLOBAL_CACHE_DIR", str(ROOT / "build/upstream/zig-cache-0.17"))}
    subprocess.run([str(zig), "build"], cwd=build, check=True, env=env)
    result = subprocess.check_output([str(build / "zig-out/bin/paste-oracle")], text=True)
    actual = [json.loads(line) for line in result.split("\n") if line]
    assert [case["name"] for case in cases] == [case["name"] for case in actual]
    fixture = ROOT / "kinetica-terminal/test/generated/TerminalPasteFixtures.kt"
    encoded = [base64.b64encode(json.dumps(case, separators=(",", ":")).encode()).decode() for case in actual]
    fixture.write_text('// Generated by scripts/generate-terminal-paste.py; do not edit.\npackage io.heapy.kinetica.terminal\n\ninternal fun terminalPasteFixtures(): List<String> = listOf(\n' + ''.join('    listOf(' + ', '.join('"' + value[i:i+30000] + '"' for i in range(0, len(value), 30000)) + ').joinToString(""),\n' for value in encoded) + ')\n')
    digest = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
    manifest = dict(commit=SHA, zig=subprocess.check_output([str(zig), "version"], text=True).strip(),
        cases=len(actual), encodings=len(actual) * 2, safetyChecks=len(actual) * 3, helperSha256=digest(helper),
        generatorSha256=digest(Path(__file__)), fixtureSha256=digest(fixture),
        sources={path: digest(upstream / path) for path in ["src/input/paste.zig", "src/lib_vt.zig", "src/terminal/paste.zig", "src/Surface.zig"]})
    (ROOT / "kinetica-terminal/test-upstream/ghostty/paste-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f'Generated {len(actual)} paste cases / {manifest["encodings"]} encodings / {manifest["safetyChecks"]} safety checks')


if __name__ == "__main__":
    main()
