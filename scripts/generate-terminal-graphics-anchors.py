#!/usr/bin/env python3
"""Snapshot real libghostty placement pins while its terminal scrolls and resizes."""
import hashlib
import json
from pathlib import Path
import runpy
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
COMMON = runpy.run_path(str(ROOT / "scripts/generate-terminal-oracle.py"))


def cases():
    result = []
    for text in ("", "abcdefghijklmno", "abc\r\ndef", "ab界cd界ef", "界界界界界", "áb👩‍💻c", "\x1bM", "\n\n"):
        for positions in ([(1,0,0)], [(1,7,0),(2,6,2),(3,1,4)], [(1,2,0),(2,3,0),(3,7,0)],
                          [(1,7,0),(2,3,0),(3,2,0)], [(1,7,2),(2,3,2),(3,2,2)]):
            events = [{"write":text}] + [{"anchor":list(p)} for p in positions]
            events += [{"write":"\x1b[1;1H"}]
            events += [{"resize":[w,h]} for w,h in [(5,5),(3,3),(1,3),(9,6),(8,5)]]
            result.append(dict(name=f"reflow_{text}_{positions}",events=events))
    result += [
        dict(name="history_reflow",events=[{"write":"abcdefghijklmno"},{"anchor":[1,3,0]},
            {"anchor":[2,7,4]},{"write":"\x1b[5;1H\r\nsecond\r\nthird"},
            {"resize":[4,5]},{"resize":[12,8]},{"resize":[2,3]},{"resize":[8,5]}]),
        dict(name="overwrite_keeps_pins",events=[{"anchor":[1,3,2]},{"write":"\x1b[3;1Habcdefgh\r\x1b[2K"},
            {"resize":[4,5]},{"write":"\x1b[3;1H123456"},{"resize":[10,5]}]),
        dict(name="history_clear",anchorPolicy="retire-cleared-history",events=[{"anchor":[1,3,0]},{"anchor":[2,4,4]},
            {"write":"\x1b[5;1H\n\n"},{"write":"\x1b[3J"},{"resize":[4,5]}]),
        dict(name="inactive_screen_resize",events=[{"write":"abcdefghijklmno"},{"anchor":[1,6,0]},
            {"write":"\x1b[?47h"},{"anchor":[2,7,3]},{"resize":[4,3]},
            {"write":"\x1b[?47l"},{"resize":[10,7]},{"write":"\x1b[?47h"},
            {"write":"\x1b[?47l"}]),
        dict(name="saved_cursor_and_pins",events=[{"anchor":[1,6,2]},{"write":"\x1b[3;8H\x1b7\x1b[H"},
            {"anchor":[2,4,2]},{"resize":[4,5]},{"resize":[2,3]},
            {"write":"\x1b8"},{"resize":[9,6]}]),
    ]
    return result


def commands(case):
    result = ["N 8 5 1000", "C " + " ".join(f"{v:x}" for v in COMMON["DEFAULT_COLORS"] + COMMON["DEFAULT_PALETTE"]),
              "G 1000000 1 2 3", "J", "R 8 5 8 16"]
    for event in case["events"]:
        if "resize" in event:
            w,h=event["resize"]
            result.append(f"R {w} {h} 8 16")
        else:
            if "anchor" in event:
                ident,x,y=event["anchor"]
                # Tall placements expose pins in retained history through the viewport API.
                value=f"\x1b[{y+1};{x+1}H\x1b_Ga=T,C=1,f=24,s=1,v=1,c=1,r=1000,i={ident},p={ident};AAAA\x1b\\"
            else:
                value=event["write"]
            result.append("W "+value.encode().hex())
        result.append("S")
    return result


def main():
    upstream=Path(sys.argv[1]).resolve()
    if subprocess.check_output(["git","rev-parse","HEAD"],cwd=upstream,text=True).strip()!=COMMON["SHA"]:
        raise SystemExit("Wrong Ghostty revision")
    subprocess.run(["git","diff","--exit-code","HEAD","--","."],cwd=upstream,check=True,stdout=subprocess.DEVNULL)
    build=ROOT/"build/terminal-oracle"
    build.mkdir(exist_ok=True,parents=True)
    helper=build/"ghostty-anchor-oracle"
    library=upstream/"zig-out/lib"
    subprocess.run(["cc","-std=c11","-Wall","-Wextra","-Werror","-I",str(upstream/"include"),str(ROOT/"scripts/terminal-ghostty-oracle.c"),
                    "-L",str(library),"-lghostty-vt","-Wl,-rpath,"+str(library),"-o",str(helper)],check=True)
    corpus=cases()
    for case in corpus:
        result=subprocess.run([str(helper)],input="\n".join(commands(case))+"\n",text=True,capture_output=True)
        if result.returncode:
            raise RuntimeError(case["name"]+": "+result.stderr)
        snapshots=[json.loads(line) for line in result.stdout.splitlines()]
        assert len(snapshots)==len(case["events"])
        case["snapshots"]=[{key:s[key] for key in ("kittyPlacements","cursor","pendingWrap","history","alternate")} for s in snapshots]
    output='// Generated by scripts/generate-terminal-graphics-anchors.py; do not edit.\n'
    output+='// Original libghostty-vt '+COMMON["SHA"]+' (MIT).\npackage io.heapy.kinetica.terminal\n\n'
    output+='internal fun terminalGraphicsAnchorFixtures(): String = '+COMMON["encoded"](corpus)+'\n'
    COMMON["write_generated"](ROOT/"kinetica-terminal/test/generated/TerminalGraphicsAnchorFixtures.kt",output)
    manifest={"commit":COMMON["SHA"],"cases":len(corpus),"snapshots":sum(len(c["events"]) for c in corpus),
              "generatorSha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "helperSha256":hashlib.sha256((ROOT/"scripts/terminal-ghostty-oracle.c").read_bytes()).hexdigest(),
              "librarySha256":hashlib.sha256((library/"libghostty-vt.0.dylib").read_bytes()).hexdigest(),
              "fixturesSha256":hashlib.sha256(output.encode()).hexdigest()}
    COMMON["write_generated"](ROOT/"kinetica-terminal/test-upstream/ghostty/graphics-anchors-manifest.json",json.dumps(manifest,indent=2)+"\n")
    print(f'Generated {len(corpus)} anchor cases and {manifest["snapshots"]} snapshots')


if __name__=="__main__":
    main()
