#!/usr/bin/env python3
"""Graphics resident-storage accounting oracle using the unmodified pinned Ghostty Zig module."""
import base64
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SHA = "83fb95624b0439ee660c2679b43b38c8b63769cd"


def cases():
    result = []
    def apc(header, data=b''):
        return '\x1b_G'+header+';'+base64.b64encode(data).decode()+'\x1b\\'
    def image(ident, width=1):
        return apc(f'a=T,i={ident},f=24,s={width},v=1,p=7,C=1', bytes(range(1, width*3+1)))
    def frame(fields=''):
        return apc('a=f,i=1,f=32,s=1,v=1'+(','+fields if fields else ''), b'\x14\x28\x3c\xff')
    def add(name, limit, events):
        result.append(dict(name=name,limit=limit,events=[dict(text=e) if isinstance(e,str) else e for e in events]))
    for width in [1,2]:
        for limit in sorted({width*3,width*3+1,width*4,width*8-1,width*8,width*8+3}):
            add(f'root_conversion_{width}_{limit}',limit,[image(1,width),frame(),frame('r=1'),
                dict(limit=limit),image(2),frame(),dict(limit=limit+8),image(3)])
    for limit in [6,7,8,12,16]:
        add(f'composition_conversion_{limit}',limit,[image(1,2),
            apc('a=c,i=1,r=1,c=1,w=1,h=1,x=1,X=0,C=1'),
            apc('a=c,i=1,r=1,c=1,w=1,h=1,x=0,X=0,C=1'),
            frame(),dict(limit=limit),image(2),dict(limit=3),dict(limit=0)])
    for changed in [3,4,8,16,0]:
        add(f'limit_during_frame_chunks_{changed}',8,[image(1),
            apc('a=f,i=1,f=32,s=1,v=1,m=1',b'\x14'),dict(limit=changed),
            apc('a=f',b'\x28\x3c\xff'),dict(limit=16),image(2)])
        add(f'limit_during_apc_{changed}',8,[image(1),
            '\x1b_Ga=f,i=1,f=32,s=1,v=1;FC',dict(limit=changed),
            'g8/w==\x1b\\',dict(limit=16),image(2)])
    add('conversion_on_both_screens',3,[image(1),frame(),'\x1b[?47h',image(2),
        '\x1b[?47l',dict(limit=3),'\x1b[?47h','\x1b[?47l',image(3)])
    return result


def main():
    upstream = Path(sys.argv[1]).resolve()
    zig = Path(sys.argv[2]).resolve()
    assert subprocess.check_output(["git","rev-parse","HEAD"],cwd=upstream,text=True).strip() == SHA
    subprocess.run(["git","diff","--exit-code","HEAD","--","."],cwd=upstream,check=True,stdout=subprocess.DEVNULL)
    build = ROOT/"build/terminal-graphics-accounting-oracle"
    build.mkdir(parents=True,exist_ok=True)
    corpus = cases()
    (build/"cases.json").write_text(json.dumps(corpus,ensure_ascii=True))
    helper = ROOT/"scripts/terminal-ghostty-graphics-accounting-oracle.zig"
    shutil.copyfile(helper,build/"main.zig")
    (build/"build.zig.zon").write_text('.{ .name = .zig_vt_stream, .version = "0.0.0", .fingerprint = 0x34c1f71303690b3f, .minimum_zig_version = "0.17.0", .dependencies = .{ .ghostty = .{ .path = '+json.dumps(os.path.relpath(upstream,build))+' } }, .paths = .{""} }')
    (build/"build.zig").write_text('''const std = @import("std");
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dep = b.dependency("ghostty", .{ .target = target, .optimize = .safe, .simd = false, .@"emit-lib-vt" = true, .@"emit-xcframework" = false });
    const root = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = target, .optimize = .safe, .link_libc = true });
    root.addImport("ghostty-vt", dep.module("ghostty-vt"));
    b.installArtifact(b.addExecutable(.{ .name = "graphics-accounting-oracle", .root_module = root }));
}
''')
    env = os.environ | {"ZIG_GLOBAL_CACHE_DIR":os.environ.get("ZIG_GLOBAL_CACHE_DIR",str(ROOT/"build/upstream/zig-cache-0.17"))}
    subprocess.run([str(zig),"build"],cwd=build,check=True,env=env)
    output = subprocess.run([str(build/"zig-out/bin/graphics-accounting-oracle")],capture_output=True,text=True)
    if output.returncode: print(output.stderr,file=sys.stderr)
    output.check_returncode()
    actual = [json.loads(line) for line in output.stdout.splitlines()]
    assert len(corpus) == len(actual)
    for case, result in zip(corpus,actual):
        assert case["name"] == result["name"]
        case["snapshots"] = result["snapshots"]
    fixture = ROOT/"kinetica-terminal/test/generated/TerminalGraphicsAccountingFixtures.kt"
    encoded = [base64.b64encode(json.dumps(c,separators=(',',':')).encode()).decode() for c in corpus]
    fixture.write_text('// Generated by scripts/generate-terminal-graphics-accounting.py; do not edit.\npackage io.heapy.kinetica.terminal\n\ninternal fun terminalGraphicsAccountingFixtures(): List<String> = listOf(\n'+''.join('    "'+v+'",\n' for v in encoded)+')\n')
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    manifest = dict(commit=SHA,zig=subprocess.check_output([str(zig),"version"],text=True).strip(),
        cases=len(corpus),snapshots=sum(len(c["snapshots"]) for c in corpus),

        helperSha256=digest(helper),generatorSha256=digest(Path(__file__)),fixtureSha256=digest(fixture),
        sources={p:digest(upstream/p) for p in ["src/terminal/Terminal.zig","src/terminal/stream_terminal.zig","src/terminal/stream.zig","src/terminal/Parser.zig","src/terminal/kitty/graphics_storage.zig","src/terminal/kitty/graphics_exec.zig"]})
    (ROOT/"kinetica-terminal/test-upstream/ghostty/graphics-accounting-manifest.json").write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Generated {len(corpus)} graphics accounting cases / {manifest["snapshots"]} checkpoints')


if __name__ == "__main__": main()
