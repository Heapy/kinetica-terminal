#!/usr/bin/env node
// Runs the pinned, unmodified Ghostty GLSL functions in WebGL2.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = resolve(process.argv[2] ?? `${root}/build/upstream/ghostty-1.4.0`);
const pin = JSON.parse(readFileSync(`${root}/kinetica-terminal/third-party/ghostty.json`));
assert.equal(execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim(), pin.commit);
execFileSync('git', ['diff', '--exit-code', 'HEAD', '--', '.'], { cwd: upstream });
const source = readFileSync(`${upstream}/src/renderer/shaders/glsl/common.glsl`, 'utf8');
const start = source.indexOf('float luminance(vec3 color)');
const load = source.indexOf('vec4 load_color(', start);
const end = source.indexOf('\n}', load) + 2;
assert.ok(start >= 0 && load > start && end > load);
const functions = source.slice(start, end);
const colors = [0, 0xffffff, 0x010101, 0x0a0a0a, 0x0b0b0b, 0x404040, 0x757575, 0x808080, 0xbfbfbf, 0xff0000, 0x00ff00, 0x0000ff, 0x123456];
const cases = [];
for (const fg of colors) for (const bg of colors) for (const alpha of [0, 1, 26, 128, 230, 255])
  for (const minimum of [1, 1.1, 3, 4.5, 7, 21]) cases.push([minimum, fg, bg, alpha]);
let seed = 0x140c0de;
const random = () => (seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0);
for (let i = 0; i < 2048; i++) cases.push([1 + random() / 0x100000000 * 20, random() & 0xffffff, random() & 0xffffff, random() & 255]);
const { chromium } = await import(process.env.PLAYWRIGHT_IMPORT ?? 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
let browserVersion;
try {
  browserVersion = browser.version();
  const page = await browser.newPage();
  const results = await page.evaluate(({ functions, cases }) => {
    const canvas = document.createElement('canvas'); canvas.width = 1; canvas.height = 1;
    const gl = canvas.getContext('webgl2', { antialias: false });
    if (!gl) throw new Error('WebGL2 unavailable');
    const compile = (type, source) => {
      const shader = gl.createShader(type); gl.shaderSource(shader, source); gl.compileShader(shader);
      if (!gl.getShaderParameter(shader, gl.COMPILE_STATUS)) throw new Error(gl.getShaderInfoLog(shader));
      return shader;
    };
    const vertex = compile(gl.VERTEX_SHADER, `#version 300 es
      void main() { vec2 p = vec2(float((gl_VertexID << 1) & 2), float(gl_VertexID & 2)); gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0); }`);
    const fragment = compile(gl.FRAGMENT_SHADER, `#version 300 es
      precision highp float; precision highp int;
      ${functions}
      uniform uvec4 foreground; uniform uvec4 background; uniform float minimum;
      out vec4 result;
      void main() {
        vec4 fg = load_color(foreground, true);
        vec4 corrected = contrasted_color(minimum, fg, load_color(background, true));
        result = all(equal(corrected, fg)) ? vec4(0,1,0,1) : corrected.r == 1.0 ? vec4(0,0,1,1) : vec4(1,0,0,1);
      }`);
    const program = gl.createProgram(); gl.attachShader(program, vertex); gl.attachShader(program, fragment); gl.linkProgram(program);
    if (!gl.getProgramParameter(program, gl.LINK_STATUS)) throw new Error(gl.getProgramInfoLog(program));
    gl.useProgram(program); gl.disable(gl.DITHER);
    const fg = gl.getUniformLocation(program, 'foreground'), bg = gl.getUniformLocation(program, 'background');
    const minimum = gl.getUniformLocation(program, 'minimum');
    const pixel = new Uint8Array(4);
    return cases.map(([min, f, b, alpha]) => {
      gl.uniform4ui(fg, f >> 16, f >> 8 & 255, f & 255, alpha);
      gl.uniform4ui(bg, b >> 16, b >> 8 & 255, b & 255, 255); gl.uniform1f(minimum, min);
      gl.drawArrays(gl.TRIANGLES, 0, 3); gl.readPixels(0, 0, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixel);
      if (gl.getError() !== gl.NO_ERROR || pixel[3] !== 255) throw new Error('Oracle draw failed');
      return pixel[1] === 255 ? -1 : pixel[2] === 255 ? 0xffffff : 0;
    });
  }, { functions, cases });
  cases.forEach((c, i) => c.push(results[i]));
} finally { await browser.close(); }
const fixture = `${root}/kinetica-terminal/test/generated/TerminalContrastFixtures.kt`;
const chunks = [];
for (let i = 0; i < cases.length; i += 128) chunks.push(Buffer.from(JSON.stringify(cases.slice(i, i + 128))).toString('base64'));
writeFileSync(fixture, '// Generated by scripts/generate-terminal-contrast.mjs; do not edit.\npackage io.heapy.kinetica.terminal\n\ninternal fun terminalContrastFixtures(): List<String> = listOf(\n' + chunks.map(c => `    "${c}",\n`).join('') + ')\n');
const digest = path => createHash('sha256').update(readFileSync(path)).digest('hex');
const manifest = { commit: pin.commit, browser: browserVersion, cases: cases.length,
  generatorSha256: digest(fileURLToPath(import.meta.url)), fixtureSha256: digest(fixture),
  extractedFunctionsSha256: createHash('sha256').update(functions).digest('hex'),
  sources: Object.fromEntries(['src/renderer/shaders/glsl/common.glsl', 'src/renderer/shaders/glsl/cell_text.v.glsl', 'src/renderer/shaders/glsl/cell_text.f.glsl', 'src/renderer/cell.zig', 'src/config/Config.zig'].map(path => [path, digest(`${upstream}/${path}`)])) };
writeFileSync(`${root}/kinetica-terminal/test-upstream/ghostty/contrast-manifest.json`, JSON.stringify(manifest, null, 2) + '\n');
console.log(`Generated ${cases.length} contrast decisions from original Ghostty GLSL`);
