#!/usr/bin/env node
// Run the pinned original AppKit flagsChanged callback against real NSEvents.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = resolve(process.argv[2] ?? `${root}/build/upstream/ghostty-1.4.0`);
const pin = JSON.parse(readFileSync(`${root}/kinetica-terminal/third-party/ghostty.json`));
assert.equal(execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim(), pin.commit);
execFileSync('git', ['diff', '--exit-code', 'HEAD', '--', '.'], { cwd: upstream });
const sourcePaths = ['macos/Sources/Ghostty/Surface View/SurfaceView_AppKit.swift',
  'macos/Sources/Ghostty/Ghostty.Input.swift', 'include/ghostty.h'];
function extract(path, signature) {
  const source = readFileSync(`${upstream}/${path}`, 'utf8');
  const start = source.indexOf(signature); assert.ok(start >= 0);
  let end = source.indexOf('{', start), depth = 1;
  while (depth && ++end < source.length) {
    if (source[end] === '{') depth++;
    else if (source[end] === '}') depth--;
  }
  assert.equal(depth, 0); return source.slice(start, end + 1);
}
const callback = extract(sourcePaths[0], 'override func flagsChanged(with event: NSEvent)');
const mods = extract(sourcePaths[1], 'static func ghosttyMods(_ flags: NSEvent.ModifierFlags)');
const build = `${root}/build/native-modifier-oracle`; mkdirSync(build, { recursive: true });
writeFileSync(`${build}/bridge.h`, `#include "${upstream}/include/ghostty.h"\n#include <IOKit/hidsystem/IOLLEvent.h>\n`);
writeFileSync(`${build}/main.swift`, `import AppKit
enum Ghostty { ${mods} }
final class Harness: NSResponder {
    var marked = false
    var result: Int = -1
    func hasMarkedText() -> Bool { marked }
    func keyAction(_ action: ghostty_input_action_e, event: NSEvent) -> Bool {
        result = Int(action.rawValue); return true
    }
    ${callback}
}
let harness = Harness()
let keys: [UInt16] = [56, 60, 59, 62, 58, 61, 55, 54, 57, 0]
let aggregate: [UInt] = [1 << 16, 1 << 17, 1 << 18, 1 << 19, 1 << 20]
let sides: [UInt] = [UInt(NX_DEVICERSHIFTKEYMASK), UInt(NX_DEVICERCTLKEYMASK), UInt(NX_DEVICERALTKEYMASK), UInt(NX_DEVICERCMDKEYMASK)]
for marked in [false, true] {
    harness.marked = marked
    for mask in 0..<512 {
        var flags: UInt = 0
        for (bit, flag) in (aggregate + sides).enumerated() where mask & (1 << bit) != 0 { flags |= flag }
        var results = [String(flags), marked ? "1" : "0"]
        for key in keys {
            let event = NSEvent.keyEvent(with: .flagsChanged, location: .zero,
                modifierFlags: NSEvent.ModifierFlags(rawValue: flags), timestamp: 0,
                windowNumber: 0, context: nil, characters: "", charactersIgnoringModifiers: "",
                isARepeat: false, keyCode: key)!
            harness.result = -1; harness.flagsChanged(with: event)
            results.append(String(harness.result))
        }
        print(results.joined(separator: ","))
    }
}
`);
execFileSync('xcrun', ['swiftc', '-I', `${upstream}/include`, '-import-objc-header', `${build}/bridge.h`, `${build}/main.swift`, '-o', `${build}/oracle`], { stdio: 'inherit' });
const output = execFileSync(`${build}/oracle`, { encoding: 'utf8' }).trim();
const rows = output.split('\n'); assert.equal(rows.length, 1024);
assert.ok(rows.every(row => row.split(',').length === 12));
const fixture = `${root}/kinetica-terminal/test@macosArm64/generated/NativeModifierEventFixtures.kt`;
mkdirSync(dirname(fixture), { recursive: true });
writeFileSync(fixture, `// Generated by scripts/generate-native-modifier-events.mjs; do not edit.
package io.heapy.kinetica.terminal

// flags, preedit, actions for key codes 56,60,59,62,58,61,55,54,57,0; -1 means ignored.
internal val nativeModifierEventFixtures: String = """
${output}
""".trimIndent()
`);
const digest = path => createHash('sha256').update(readFileSync(path)).digest('hex');
writeFileSync(`${root}/kinetica-terminal/test-upstream/ghostty/native-modifier-manifest.json`, JSON.stringify({
  commit: pin.commit, events: rows.length * 10,
  swift: execFileSync('xcrun', ['swiftc', '--version'], { encoding: 'utf8' }).trim(),
  generatorSha256: digest(fileURLToPath(import.meta.url)), fixtureSha256: digest(fixture),
  sources: Object.fromEntries(sourcePaths.map(path => [path, digest(`${upstream}/${path}`)])),
  harness: 'Unmodified flagsChanged and ghosttyMods; NSResponder host captures keyAction; original C enums and SDK device masks; real NSEvents.',
}, null, 2) + '\n');
console.log(`Generated ${rows.length * 10} original Ghostty AppKit modifier actions`);
