#!/usr/bin/env python3
"""Original Zig-module placeholder oracle and pinned diacritic data; no upstream edits."""
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SHA = "4da7523faba68ccb4042ea20585817098a51c015"
PLACEHOLDER = chr(0x10EEEE)

def cases(diacritics):
    def placeholder(row=None, col=None, high=None):
        return PLACEHOLDER + ''.join(chr(diacritics[v]) if v >= 0 else '\u0300' for v in (row, col, high) if v is not None)
    def image(id=1, width=13, height=7, fields="c=4,r=3,U=1,p=7"):
        return '\x1b_Ga=T,q=2,C=1,i=%d,f=24,s=%d,v=%d,%s;%s\x1b\\' % (id, width, height, fields, base64.b64encode(bytes(width*height*3)).decode())
    def text(value): return {"text": value}
    result = []
    prefix = '\x1b[?2027h\x1b[38;2;0;0;1m'
    patterns = [placeholder(), placeholder(0,0)*3, placeholder(1,2)+PLACEHOLDER*3,
                placeholder(1,2)+placeholder(1,3)+placeholder(1,5),
                placeholder(0,0,1)+PLACEHOLDER+placeholder(0,2,0),
                placeholder(-1,-1,-1)+PLACEHOLDER, placeholder(294,294,294),
                placeholder(0,0)+"x"+PLACEHOLDER, placeholder(0,0)+"\r\n"+PLACEHOLDER,
                placeholder(0,0)+"\x1b[58;5;7m"+PLACEHOLDER+"\x1b[59m"+PLACEHOLDER,
                "\x1b[38;5;1m"+placeholder(0,0)+"\x1b[38;2;0;0;1m"+PLACEHOLDER,
                placeholder(0,0)+chr(diacritics[4])+chr(diacritics[5])+PLACEHOLDER]
    for i, pattern in enumerate(patterns):
        result.append(dict(name=f"runs_{i}", events=[text(prefix + image() + pattern)]))
    for i in range(len(diacritics)):
        high = i if i <= 255 else 0
        result.append(dict(name=f"diacritic_{i}", events=[text(prefix + image(id=1+(high<<24)) + placeholder(i,i,i) + PLACEHOLDER)]))
    for width,height in [(1,1),(13,7),(7,13),(2,48),(48,2)]:
        for cw,ch in [(8,16),(7,13),(1,1)]:
            for fields in ["U=1,p=7", "U=1,p=7,c=4", "U=1,p=7,r=3", "U=1,p=7,c=4,r=3", "U=1,p=7,c=4,r=3,x=2,y=1,w=1,h=1,z=5"]:
                lines = [''.join(placeholder(y,x) for x in range(6)) for y in range(5)]
                result.append(dict(name=f"geometry_{width}_{height}_{cw}_{ch}_{fields}", cell=[cw,ch], events=[text(prefix+image(width=width,height=height,fields=fields)+'\r\n'.join(lines))]))
    result.append(dict(name="lifecycle", events=[text(prefix+image()+placeholder(0,0)+PLACEHOLDER*5), text('\x1b[6;1H\n'), {"scroll":-1},
        {"resize":[4,6,7,13]},text('\x1b[?1049h'),{"text":'\x1b[?1049l',"scroll":1000},text('\x1b_Ga=d,d=A,q=2\x1b\\')]))
    result.append(dict(name="target_selection", events=[text(prefix+image()+placeholder(0,0)),
        text('\x1b_Ga=p,i=1,q=2,U=1,p=3,c=2,r=2\x1b\\'),
        text('\x1b[58;2;0;0;7m'+placeholder(1,1)), text('\x1b[58;5;9m'+placeholder(0,0)),
        text('\x1b_Ga=p,i=1,q=2,p=9,C=1,c=3,r=1\x1b\\'),
        text('\x1b_Ga=d,d=i,i=1,p=3,q=2\x1b\\')]))
    for field in ['c=65536,r=2','c=2,r=4294967295']:
        result.append(dict(name='grid_limit_'+field, events=[text(prefix+image(fields='U=1,p=7,'+field)+placeholder(0,0))]))
    result.append(dict(name="unsigned_id", events=[text(image(id=4294967295)+'\x1b[38;2;255;255;255m'+placeholder(0,0,255)+PLACEHOLDER)]))
    result.append(dict(name="legacy_and_palette",events=[text(image()+'\x1b[?2027l\x1b[38;5;1m'+placeholder(0,0)),
        text('\x1b]4;1;#ffffff\x07'),text('\x1b[1;2;7;8m'+placeholder(0,1))]))
    return result

def main():
    upstream = Path(sys.argv[1]).resolve()
    zig = Path(sys.argv[2]).resolve()
    assert subprocess.check_output(["git","rev-parse","HEAD"],cwd=upstream,text=True).strip() == SHA
    subprocess.run(["git","diff","--exit-code","HEAD","--","."],cwd=upstream,check=True,stdout=subprocess.DEVNULL)
    source = upstream/"src/terminal/kitty/graphics_unicode.zig"
    data = source.read_text().split('const diacritics: []const u21 = &.{',1)[1].split('};',1)[0]
    diacritics = [int(value,16) for value in re.findall(r'0x([0-9A-Fa-f]+)',data)]
    generated = ROOT/"kinetica-terminal/src/TerminalGraphicsDiacritics.kt"
    generated.write_text('// Generated by scripts/generate-terminal-graphics-unicode.py; do not edit.\n'
        '// Ghostty '+SHA+', src/terminal/kitty/graphics_unicode.zig (MIT).\n'
        '// Copyright (c) 2024 Mitchell Hashimoto, Ghostty contributors. See third-party/GHOSTTY-LICENSE.\n'
        'package io.heapy.kinetica.terminal\n\ninternal val terminalGraphicsDiacritics: IntArray = intArrayOf(\n'+
        ''.join('    '+', '.join(hex(v) for v in diacritics[i:i+10])+',\n' for i in range(0,len(diacritics),10))+')\n')
    build = ROOT/"build/terminal-unicode-oracle"
    build.mkdir(parents=True,exist_ok=True)
    corpus = cases(diacritics)
    (build/"cases.json").write_text(json.dumps(corpus,ensure_ascii=True))
    shutil.copyfile(ROOT/"scripts/terminal-ghostty-unicode-oracle.zig",build/"main.zig")
    (build/"build.zig.zon").write_text('.{ .name = .zig_vt_stream, .version = "0.0.0", .fingerprint = 0x34c1f71303690b3f, .minimum_zig_version = "0.16.0", .dependencies = .{ .ghostty = .{ .path = '+json.dumps(os.path.relpath(upstream,build))+' } }, .paths = .{""} }')
    (build/"build.zig").write_text('''const std = @import("std");
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dep = b.dependency("ghostty", .{ .target = target, .optimize = .ReleaseSafe, .simd = false, .@"emit-lib-vt" = true, .@"emit-xcframework" = false });
    const root = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = target, .optimize = .ReleaseSafe, .link_libc = true });
    root.addImport("ghostty-vt", dep.module("ghostty-vt"));
    b.installArtifact(b.addExecutable(.{ .name = "unicode-oracle", .root_module = root }));
}
''')
    environment = os.environ | {"ZIG_GLOBAL_CACHE_DIR": os.environ.get("ZIG_GLOBAL_CACHE_DIR", str(ROOT/"build/upstream/zig-cache"))}
    subprocess.run([str(zig),"build"],cwd=build,check=True,env=environment)
    result = subprocess.run([str(build/"zig-out/bin/unicode-oracle")],capture_output=True,check=True,text=True)
    snapshots = [json.loads(line) for line in result.stdout.splitlines()]
    assert len(snapshots) == len(corpus)
    for case, actual in zip(corpus,snapshots):
        assert case['name'] == actual['name']
        case['snapshots'] = actual['snapshots']
    encoded = [base64.b64encode(json.dumps(c,separators=(',',':')).encode()).decode() for c in corpus]
    fixture = ROOT/"kinetica-terminal/test/generated/TerminalGraphicsUnicodeFixtures.kt"
    fixture.write_text('// Generated by scripts/generate-terminal-graphics-unicode.py; do not edit.\npackage io.heapy.kinetica.terminal\n\ninternal fun terminalGraphicsUnicodeFixtures(): List<String> = listOf(\n'+''.join('    "'+value+'",\n' for value in encoded)+')\n')
    manifest = dict(commit=SHA,zig=subprocess.check_output([str(zig),'version'],text=True).strip(),cases=len(corpus),snapshots=sum(len(c['snapshots']) for c in corpus),
        sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),helperSha256=hashlib.sha256((ROOT/'scripts/terminal-ghostty-unicode-oracle.zig').read_bytes()).hexdigest(),
        generatorSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),fixtureSha256=hashlib.sha256(fixture.read_bytes()).hexdigest(),diacriticsSha256=hashlib.sha256(generated.read_bytes()).hexdigest())
    (ROOT/'kinetica-terminal/test-upstream/ghostty/graphics-unicode-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f"Generated {len(corpus)} original-libghostty placeholder cases")

if __name__ == '__main__': main()
