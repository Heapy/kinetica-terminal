#!/usr/bin/env python3
"""Native release fixtures: explicit current-layout identity, no press-time text.

The unchanged AppKit keyUp/keyAction/NSEvent.ghosttyKeyEvent path supplies these
fields to embedded KeyEvent.core. Execute the pinned original libghostty encoder;
no Kinetica output and no changes to the user's keyboard layout are involved.
"""
import hashlib
import json
from pathlib import Path
import runpy
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
upstream = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / 'build/upstream/ghostty-1.4.0'
pin = json.loads((ROOT / 'kinetica-terminal/third-party/ghostty.json').read_text())
assert subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=upstream, text=True).strip() == pin['commit']
subprocess.run(['git', 'diff', '--exit-code', 'HEAD', '--', '.'], cwd=upstream, check=True)
build = ROOT / 'build/native-key-release-oracle'
build.mkdir(parents=True, exist_ok=True)
helper = ROOT / 'scripts/terminal-ghostty-oracle.c'
library = upstream / 'zig-out/lib'
executable = build / 'oracle'
subprocess.run(['cc', '-std=c11', '-Wall', '-Wextra', '-Werror', '-I', str(upstream / 'include'),
                str(helper), '-L', str(library), '-lghostty-vt', '-Wl,-rpath,' + str(library),
                '-o', str(executable)], check=True)
config = runpy.run_path(str(ROOT / 'scripts/generate-terminal-oracle.py'))
colors = 'C ' + ' '.join(f'{color:06x}' for color in config['DEFAULT_COLORS'] + config['DEFAULT_PALETTE'])
keys = [('A', 0, cp) for cp in [97, 1092, 113, 0, 128512]] + [
    ('DIGIT_1', 18, 49), ('SEMICOLON', 41, 59), ('ENTER', 36, 13),
    ('ARROW_UP', 126, 0xf700), ('NUMPAD_1', 83, 49)]
rows = []
commands = []
for flags in [0, 3, 15, 31]:
    for mods in list(range(16)) + [64, 65]:
        for key, code, unshifted in keys:
            rows.append((flags, mods, code, unshifted))
            commands += ['N 2 1 1', colors, 'W ' + f'\x1b[>{flags}u'.encode().hex(),
                         f'E {key} {mods} {mods & ~12} 2 {unshifted} -', 'S']
result = subprocess.run([str(executable)], input='\n'.join(commands) + '\n', text=True, capture_output=True, check=True)
outputs = [json.loads(line)['replies'] for line in result.stdout.splitlines()]
assert len(rows) == len(outputs) == 720
fixture = ROOT / 'kinetica-terminal/test@macosArm64/generated/NativeKeyReleaseFixtures.kt'
fixture.write_text('// Generated by scripts/generate-native-key-releases.py; do not edit.\n'
                   'package io.heapy.kinetica.terminal\n\n'
                   '// Kitty flags, modifiers, native key code, current unshifted codepoint, output hex.\n'
                   'internal val nativeKeyReleaseFixtures: String = """\n' +
                   '\n'.join(','.join(map(str, row)) + ',' + output for row, output in zip(rows, outputs)) +
                   '\n""".trimIndent()\n')
def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
sources = ['macos/Sources/Ghostty/Surface View/SurfaceView_AppKit.swift',
           'macos/Sources/Ghostty/NSEvent+Extension.swift', 'src/apprt/embedded.zig',
           'src/input/key_encode.zig', 'src/input/key.zig']
manifest = dict(commit=pin['commit'], cases=len(rows), generatorSha256=digest(__file__),
                helperSha256=digest(helper), fixtureSha256=digest(fixture),
                sources={path: digest(upstream / path) for path in sources},
                librarySha256={p.name: digest(p) for p in library.glob('libghostty-vt.*') if p.is_file()},
                harness='Original libghostty-vt encoder; explicit current unshifted codepoint and empty release text match the inspected original AppKit/embedded path. This does not run physical layout switching.')
(ROOT / 'kinetica-terminal/test-upstream/ghostty/native-key-release-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print('Generated 720 original native key-release encodings')
