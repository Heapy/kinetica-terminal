#!/usr/bin/env python3
"""Embed the unmodified, pinned JetBrains Mono faces in the native application."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
COMMIT = "cd5227bd1f61dff3bbd6c814ceaf7ffd95e947d9"  # JetBrains Mono v2.304
SOURCE = f"https://raw.githubusercontent.com/JetBrains/JetBrainsMono/{COMMIT}"
FILES = {
    "JetBrainsMono-Regular.ttf": "a0bf60ef0f83c5ed4d7a75d45838548b1f6873372dfac88f71804491898d138f",
    "JetBrainsMono-Bold.ttf": "5590990c82e097397517f275f430af4546e1c45cff408bde4255dad142479dcb",
    "JetBrainsMono-Italic.ttf": "9d0a1f7a708e6af183f1193b7e81d40da294f5c67682c085d8401c60aac8ded4",
    "JetBrainsMono-BoldItalic.ttf": "4039d5ce0ed225bf9c8b2c8c6436290ae2f356b7e90d70fa666227238324aa3b",
    "OFL.txt": "30f0c136e3c88e422d0791acd97238870f9054a9729bc34cf2ff0d4ed8cac4ad",
}
APP = ROOT / "samples/native-terminal"
DIRECTORY = APP / "fonts/jetbrains-mono"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in artifacts offline")
    args = parser.parse_args()
    sources = {}
    for name, sha in FILES.items():
        path = DIRECTORY / name
        if not path.exists() and not args.check:
            location = f"fonts/ttf/{name}" if name.endswith(".ttf") else name
            with urllib.request.urlopen(f"{SOURCE}/{location}") as response:
                data = response.read()
            assert digest(data) == sha, f"Unexpected upstream content: {name}"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        sources[name] = path.read_bytes()
        assert digest(sources[name]) == sha, f"Changed pinned source: {name}"

    kotlin = (
        "// Generated by scripts/generate-native-text-fonts.py; do not edit.\n"
        "// JetBrains Mono v2.304, OFL-1.1; see fonts/jetbrains-mono/{OFL.txt,manifest.json}.\n"
        "package app.native.terminal\n\n"
        "internal fun bundledTerminalFontData(): Map<String, String> = mapOf(\n"
    )
    for name, data in sources.items():
        if not name.endswith(".ttf"):
            continue
        encoded = base64.b64encode(data).decode()
        kotlin += f'    "{Path(name).stem}" to listOf(\n'
        kotlin += "".join("        " + json.dumps(encoded[i:i + 16000]) + ",\n" for i in range(0, len(encoded), 16000))
        kotlin += '    ).joinToString(""),\n'
    kotlin = (kotlin + ")\n").encode()
    manifest = dict(repository="https://github.com/JetBrains/JetBrainsMono", version="2.304", commit=COMMIT,
                    source=SOURCE, files=FILES, generatorSha256=digest(Path(__file__).read_bytes()),
                    generatedSha256=digest(kotlin))
    artifacts = {
        APP / "src/generated/TerminalTextFontData.kt": kotlin,
        DIRECTORY / "manifest.json": (json.dumps(manifest, indent=2) + "\n").encode(),
    }
    for path, data in artifacts.items():
        if args.check:
            assert path.read_bytes() == data, f"Stale generated artifact: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'{"Verified" if args.check else "Generated"} four native JetBrains Mono faces')


if __name__ == "__main__":
    main()
