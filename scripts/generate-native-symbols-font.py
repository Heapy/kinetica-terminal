#!/usr/bin/env python3
"""Embed the unmodified, pinned Symbols Nerd Font in the standalone macOS engine."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
COMMIT = "fa7b859994228a9c8759f99c55a8d31ee92a1b5e"  # Nerd Fonts v3.4.0
SOURCE = f"https://raw.githubusercontent.com/ryanoasis/nerd-fonts/{COMMIT}/patched-fonts/NerdFontsSymbolsOnly"
FILES = {
    "SymbolsNerdFont-Regular.ttf": "71db104aa66567d0efe0b98758f9dfc1895573a453fe85fb53d1c38544a55106",
    "LICENSE": "84a7a98c82140fb12c37fe42b93805baa16024cb3e5acc599b7ffe612c55d847",
}
DIRECTORY = ROOT / "kinetica-terminal/fonts/nerd-symbols"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in artifacts offline")
    args = parser.parse_args()
    sources = {}
    for name, sha in FILES.items():
        path = DIRECTORY / name
        if not path.exists() and not args.check:
            with urllib.request.urlopen(f"{SOURCE}/{name}") as response:
                data = response.read()
            assert digest(data) == sha, f"Unexpected upstream content: {name}"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        sources[name] = path.read_bytes()
        assert digest(sources[name]) == sha, f"Changed pinned source: {name}"

    encoded = base64.b64encode(sources["SymbolsNerdFont-Regular.ttf"]).decode()
    kotlin = (
        "// Generated by scripts/generate-native-symbols-font.py; do not edit.\n"
        "// Symbols Nerd Font v3.4.0, MIT; see fonts/nerd-symbols/{LICENSE,manifest.json}.\n"
        "package io.heapy.kinetica.terminal\n\n"
        "internal fun terminalSymbolsFontData(): String = listOf(\n"
        + "".join("    " + json.dumps(encoded[i:i + 16000]) + ",\n" for i in range(0, len(encoded), 16000))
        + ').joinToString("")\n'
    ).encode()
    manifest = dict(repository="https://github.com/ryanoasis/nerd-fonts", version="3.4.0", commit=COMMIT,
                    source=SOURCE, files=FILES, fontBytes=len(sources["SymbolsNerdFont-Regular.ttf"]),
                    generatorSha256=digest(Path(__file__).read_bytes()), generatedSha256=digest(kotlin))
    artifacts = {
        ROOT / "kinetica-terminal/src@macosArm64/generated/TerminalSymbolsFontData.kt": kotlin,
        ROOT / "kinetica-terminal/resources/META-INF/LICENSES/NERD-FONTS-MIT.txt": sources["LICENSE"],
        DIRECTORY / "manifest.json": (json.dumps(manifest, indent=2) + "\n").encode(),
    }
    for path, data in artifacts.items():
        if args.check:
            assert path.read_bytes() == data, f"Stale generated artifact: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'{"Verified" if args.check else "Generated"} native Symbols Nerd Font ({manifest["fontBytes"]} bytes)')


if __name__ == "__main__":
    main()
