#!/usr/bin/env python3
"""ENQ answerback protocol oracle using the unmodified pinned Ghostty Zig module."""
import base64
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SHA = "83fb95624b0439ee660c2679b43b38c8b63769cd"


def cases():
    result=[]
    def add(name,events):
        result.append(dict(name=name,events=[dict(text=e) if isinstance(e,str) else e for e in events]))
    add('default_disabled',['\x05','abc\x05\x1b[6n'])
    for length in [0,1,254,255,256,257]:
        add(f'byte_limit_{length}',[dict(response=(b'x'*length).hex()),'\x05','\x05\x05'])
    for name,data in [('unicode_255',('界'*85).encode()),('unicode_258',('界'*86).encode()),
                      ('binary_zero',bytes(range(255))),('binary_ff',bytes(range(1,256)))]:
        add(name,[dict(response=data.hex()),'\x05'])
    add('host_changes',[dict(response=b'first'.hex()),'\x05',dict(response=b'second'.hex()),'\x05',dict(response='-'),'\x05'])
    add('resets_screens_hold',[dict(response=b'ready'.hex()),'abcdef\x05\x1b[6n','\x1b[!p\x05',
        '\x1b[?1049h\x05','\x1b[?1049l\x05','\x1b[?2026h\x05','\x1b[?2026l\x05','\x1bc\x05'])
    contexts={
        'escape':'\x1b\x05[6n', 'escape_intermediate':'\x1b(\x05B\x1b[6n',
        'csi_entry':'\x1b[\x056n','csi_param':'\x1b[6\x05n','csi_intermediate':'\x1b[1 \x05q\x1b[6n',
        'csi_ignore':'\x1b[:\x05n\x1b[6n', 'dcs_entry':'\x1bP\x05$qm\x1b\\',
        'dcs_param':'\x1bP1\x05$qm\x1b\\','dcs_intermediate':'\x1bP$\x05qm\x1b\\',
        'dcs_body':'\x1bP$q\x05m\x1b\\','dcs_ignore':'\x1bP:0\x05q\x1b\\',
        'osc':'\x1b]2;ab\x05cd\x07','apc':'\x1b_unknown\x05data\x1b\\',
        'sos':'\x1bXabc\x05def\x1b\\','pm':'\x1b^abc\x05def\x1b\\',
    }
    for name,text in contexts.items(): add('parser_'+name,[dict(response=b'ENQ'.hex()),text+'\x05\x1b[6n'])
    add('configure_during_partial',[dict(response=b'old'.hex()),'\x1b[6',dict(response=b'new'.hex()),'\x05n'])
    add('pending_wrap',[dict(response=b'wrap'.hex()),'abcdefghijkl\x05\x1b[6n','Z\x05\x1b[6n'])
    return result


def main():
    upstream = Path(sys.argv[1]).resolve()
    zig = Path(sys.argv[2]).resolve()
    assert subprocess.check_output(["git","rev-parse","HEAD"],cwd=upstream,text=True).strip() == SHA
    subprocess.run(["git","diff","--exit-code","HEAD","--","."],cwd=upstream,check=True,stdout=subprocess.DEVNULL)
    build = ROOT/"build/terminal-enquiry-oracle"
    build.mkdir(parents=True,exist_ok=True)
    corpus = cases()
    (build/"cases.json").write_text(json.dumps(corpus,ensure_ascii=True))
    helper = ROOT/"scripts/terminal-ghostty-enquiry-oracle.zig"
    shutil.copyfile(helper,build/"main.zig")
    (build/"build.zig.zon").write_text('.{ .name = .zig_vt_stream, .version = "0.0.0", .fingerprint = 0x34c1f71303690b3f, .minimum_zig_version = "0.17.0", .dependencies = .{ .ghostty = .{ .path = '+json.dumps(os.path.relpath(upstream,build))+' } }, .paths = .{""} }')
    (build/"build.zig").write_text('''const std = @import("std");
pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const dep = b.dependency("ghostty", .{ .target = target, .optimize = .safe, .simd = false, .@"emit-lib-vt" = true, .@"emit-xcframework" = false });
    const root = b.createModule(.{ .root_source_file = b.path("main.zig"), .target = target, .optimize = .safe, .link_libc = true });
    root.addImport("ghostty-vt", dep.module("ghostty-vt"));
    b.installArtifact(b.addExecutable(.{ .name = "enquiry-oracle", .root_module = root }));
}
''')
    env = os.environ | {"ZIG_GLOBAL_CACHE_DIR":os.environ.get("ZIG_GLOBAL_CACHE_DIR",str(ROOT/"build/upstream/zig-cache-0.17"))}
    subprocess.run([str(zig),"build"],cwd=build,check=True,env=env)
    output = subprocess.run([str(build/"zig-out/bin/enquiry-oracle")],capture_output=True,text=True)
    if output.returncode: print(output.stderr,file=sys.stderr)
    output.check_returncode()
    actual = [json.loads(line) for line in output.stdout.splitlines()]
    assert len(corpus) == len(actual)
    for case, result in zip(corpus,actual):
        assert case["name"] == result["name"]
        case["snapshots"] = result["snapshots"]
    fixture = ROOT/"kinetica-terminal/test/generated/TerminalEnquiryFixtures.kt"
    encoded = [base64.b64encode(json.dumps(c,separators=(',',':')).encode()).decode() for c in corpus]
    fixture.write_text('// Generated by scripts/generate-terminal-enquiry.py; do not edit.\npackage io.heapy.kinetica.terminal\n\ninternal fun terminalEnquiryFixtures(): List<String> = listOf(\n'+''.join('    "'+v+'",\n' for v in encoded)+')\n')
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    manifest = dict(commit=SHA,zig=subprocess.check_output([str(zig),"version"],text=True).strip(),
        cases=len(corpus),snapshots=sum(len(c["snapshots"]) for c in corpus),

        helperSha256=digest(helper),generatorSha256=digest(Path(__file__)),fixtureSha256=digest(fixture),
        sources={p:digest(upstream/p) for p in ["src/terminal/Terminal.zig","src/terminal/stream_terminal.zig","src/terminal/stream.zig","src/terminal/Parser.zig"]})
    (ROOT/"kinetica-terminal/test-upstream/ghostty/enquiry-manifest.json").write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Generated {len(corpus)} enquiry cases / {manifest["snapshots"]} checkpoints')


if __name__ == "__main__": main()
