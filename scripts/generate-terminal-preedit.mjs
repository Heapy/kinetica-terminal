#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = resolve(process.argv[2] ?? `${root}/build/upstream/ghostty-1.4.0`);
const zig = resolve(process.argv[3] ?? `${root}/build/upstream/zig-aarch64-macos-0.17.0/zig`);
const pin = JSON.parse(readFileSync(`${root}/kinetica-terminal/third-party/ghostty.json`));
assert.equal(execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim(), pin.commit);
execFileSync('git', ['diff', '--exit-code', 'HEAD', '--', '.'], { cwd: upstream });
const path = `${upstream}/src/renderer/State.zig`;
const source = readFileSync(path, 'utf8');
const start = source.indexOf('    pub fn range(\n', source.indexOf('pub const Preedit = struct'));
assert.ok(start > 0);
const stop = source.indexOf('\n    }\n};', start) + '\n    }'.length;
assert.ok(stop > start);
const original = source.slice(start, stop);
const build = `${root}/build/preedit-oracle`; mkdirSync(build, { recursive: true });
writeFileSync(`${build}/main.zig`, `const std = @import("std");
const terminalpkg = struct { const size = struct { const CellCountInt = u16; }; };
const Preedit = struct {
    const Codepoint = struct { wide: bool };
    codepoints: []const Codepoint,
${original}
};
pub fn main() void {
    var points: [5]Preedit.Codepoint = undefined;
    for (1..7) |columns| for (0..columns) |cursor| {
        for (1..6) |len| for (0..(@as(usize, 1) << @intCast(len))) |mask| {
            for (0..len) |i| points[i] = .{ .wide = mask & (@as(usize, 1) << @intCast(i)) != 0 };
            const p: Preedit = .{ .codepoints = points[0..len] };
            const r = p.range(@intCast(cursor), @intCast(columns - 1));
            std.debug.print("{d},{d},{d},{d},{d},{d},{d}\\n", .{columns,cursor,len,mask,r.start,r.end,r.cp_offset});
        };
    };
}
`);
const result = spawnSync(zig, ['run', `${build}/main.zig`], { encoding: 'utf8', maxBuffer: 1024 * 1024 });
assert.equal(result.status, 0, result.stderr);
const output = result.stderr.trim();
assert.equal(output.split('\n').length, 1302);
const fixture = `${root}/kinetica-terminal/test/generated/TerminalPreeditFixtures.kt`;
writeFileSync(fixture, `// Generated by scripts/generate-terminal-preedit.mjs; do not edit.
package io.heapy.kinetica.terminal

// columns,cursor,scalar count,wide-bit mask,start,end,scalar offset
internal val terminalPreeditFixtures: String = """
${output}
""".trimIndent()
`);
const digest = path => createHash('sha256').update(readFileSync(path)).digest('hex');
writeFileSync(`${root}/kinetica-terminal/test-upstream/ghostty/preedit-manifest.json`, JSON.stringify({ commit: pin.commit,
  cases: 1302, zig: execFileSync(zig, ['version'], { encoding: 'utf8' }).trim(),
  generatorSha256: digest(fileURLToPath(import.meta.url)), fixtureSha256: digest(fixture),
  sources: { 'src/renderer/State.zig': digest(path) },
  harness: 'Original Preedit.range function unchanged; standalone struct supplies codepoint widths and CellCountInt=u16.',
}, null, 2) + '\n');
console.log('Generated 1302 original Ghostty preedit ranges');
